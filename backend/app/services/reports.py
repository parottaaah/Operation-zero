"""Permission-aware incident report rendering (Markdown + PDF)."""

from __future__ import annotations

import io
import re
from dataclasses import dataclass
from html import escape

from sqlalchemy.orm import Session

from app.models.ai import AIAnalysis
from app.models.alerting import Alert
from app.models.identity import User, Workspace
from app.models.incident import EvidenceLink, Incident, IncidentEvent
from app.models.service import Service


@dataclass
class ReportPayload:
    content: bytes
    filename: str
    media_type: str
    redaction_level: str


def _fmt(dt) -> str:
    return dt.strftime("%Y-%m-%d %H:%M:%SZ") if dt else "—"


def _load(session: Session, incident: Incident):
    events = (
        session.query(IncidentEvent)
        .filter(IncidentEvent.incident_id == incident.id)
        .order_by(IncidentEvent.created_at.asc())
        .all()
    )
    evidence = (
        session.query(EvidenceLink)
        .filter(EvidenceLink.incident_id == incident.id)
        .order_by(EvidenceLink.created_at.asc())
        .all()
    )
    alerts = (
        session.query(Alert).filter(Alert.incident_id == incident.id).order_by(Alert.created_at.asc()).all()
    )
    analyses = (
        session.query(AIAnalysis)
        .filter(AIAnalysis.incident_id == incident.id, AIAnalysis.status == "completed")
        .order_by(AIAnalysis.created_at.desc())
        .limit(3)
        .all()
    )
    service = session.get(Service, incident.service_id) if incident.service_id else None
    owner = session.get(User, incident.owner_id) if incident.owner_id else None
    workspace = session.get(Workspace, incident.workspace_id)
    return events, evidence, alerts, analyses, service, owner, workspace


def build_markdown(
    session: Session, incident: Incident, *, redaction_level: str = "standard"
) -> tuple[str, str]:
    """Return ``(markdown, filename)``. ``viewer`` level omits raw telemetry excerpts."""
    events, evidence, alerts, analyses, service, owner, workspace = _load(session, incident)
    include_excerpts = redaction_level != "viewer"

    lines: list[str] = []
    lines.append(f"# Incident report: {incident.title}")
    lines.append("")
    lines.append("> Generated by OPERATION ZERO. Timestamps are UTC.")
    if not include_excerpts:
        lines.append("> Viewer-redacted export: raw telemetry excerpts are omitted.")
    lines.append("")
    lines.append("## At a glance")
    lines.append("")
    lines.append("| Field | Value |")
    lines.append("| --- | --- |")
    lines.append(f"| Incident ID | `{incident.id}` |")
    lines.append(f"| Workspace | {workspace.name if workspace else incident.workspace_id} |")
    lines.append(f"| Status | {incident.status.value} |")
    lines.append(f"| Severity | {incident.severity.value} |")
    lines.append(f"| Service | {service.name if service else '—'} |")
    lines.append(f"| Owner | {(owner.full_name or owner.email) if owner else 'unassigned'} |")
    lines.append(f"| Detected | {_fmt(incident.detected_at)} |")
    lines.append(f"| Acknowledged | {_fmt(incident.acknowledged_at)} |")
    lines.append(f"| Resolved | {_fmt(incident.resolved_at)} |")
    lines.append(f"| Closed | {_fmt(incident.closed_at)} |")
    lines.append("")

    lines.append("## Summary")
    lines.append("")
    lines.append(incident.summary.strip() or "_No summary recorded._")
    lines.append("")

    if alerts:
        lines.append("## Linked alerts")
        lines.append("")
        for alert in alerts:
            lines.append(
                f"- **{alert.title}** — {alert.severity.value}, observed "
                f"{alert.trigger_value:.4g} vs threshold {alert.threshold:.4g}, "
                f"{alert.occurrence_count} occurrence(s), status `{alert.status.value}`."
            )
        lines.append("")

    lines.append("## Timeline")
    lines.append("")
    if events:
        for event in events:
            actor = event.actor_label or "system"
            suffix = (
                f" (`{event.from_status}` → `{event.to_status}`)"
                if event.event_type.value == "status_change"
                else ""
            )
            lines.append(
                f"- **{_fmt(event.created_at)}** · {actor} · {event.event_type.value}: "
                f"{event.message}{suffix}"
            )
    else:
        lines.append("_No timeline entries._")
    lines.append("")

    lines.append("## Evidence")
    lines.append("")
    if evidence:
        for index, link in enumerate(evidence, start=1):
            lines.append(f"{index}. **{link.title or link.kind.value}** (`{link.kind.value}`)")
            if include_excerpts and link.excerpt:
                excerpt = link.excerpt.replace("\n", " ")[:500]
                lines.append(f"   - Excerpt: {excerpt}")
            if include_excerpts and link.url:
                lines.append(f"   - Reference: {link.url}")
            elif link.url:
                lines.append("   - Reference: withheld for viewer-level export")
    else:
        lines.append("_No evidence linked._")
    lines.append("")

    if analyses:
        lines.append("## AI-assisted analysis (human-reviewed, evidence-cited)")
        lines.append("")
        for analysis in analyses:
            output = analysis.output or {}
            lines.append(
                f"### {_fmt(analysis.created_at)} · provider `{analysis.provider}` · "
                f"model `{analysis.model_id or 'n/a'}` · prompt `{analysis.prompt_version}`"
            )
            lines.append("")
            lines.append("**Observed facts**")
            lines.append("")
            for fact in output.get("observed_facts", []):
                citations = ", ".join(fact.get("citations", [])) or "no citation"
                lines.append(f"- {fact.get('text', '')} [{citations}]")
            lines.append("")
            lines.append("**Hypotheses (unvalidated)**")
            lines.append("")
            for hypothesis in output.get("hypotheses", []):
                citations = ", ".join(hypothesis.get("citations", [])) or "no citation"
                lines.append(
                    f"- {hypothesis.get('text', '')} — confidence: "
                    f"{hypothesis.get('confidence', 'low')}, reasoning: "
                    f"{hypothesis.get('reasoning', 'n/a')} [{citations}]"
                )
            lines.append("")
            lines.append("**Missing information**")
            lines.append("")
            for item in output.get("missing_information", []):
                lines.append(f"- {item}")
            if not output.get("missing_information"):
                lines.append("- None recorded")
            lines.append("")
            lines.append("**Recommended next checks**")
            lines.append("")
            for check in output.get("recommended_next_checks", []):
                lines.append(f"- {check.get('text', '')} — {check.get('rationale', '')}")
            lines.append("")

    lines.append("## Resolution")
    lines.append("")
    lines.append(incident.resolution_note.strip() or "_Incident not yet resolved._")
    lines.append("")
    if incident.follow_up_actions:
        lines.append("## Follow-up actions")
        lines.append("")
        for action in incident.follow_up_actions:
            state = "done" if action.get("done") else "open"
            owner_label = action.get("owner") or "unassigned"
            lines.append(
                f"- [{'x' if action.get('done') else ' '}] {action.get('text', '')} ({owner_label}, {state})"
            )
        lines.append("")

    lines.append("---")
    lines.append("")
    lines.append(
        "AI content is advisory. Every fact above references a stored evidence item; "
        "hypotheses are not validated root causes and must be checked by a human."
    )
    lines.append("")

    markdown = "\n".join(lines)
    safe_name = re.sub(r"[^a-z0-9]+", "-", incident.title.lower()).strip("-")[:60] or "incident"
    filename = f"incident-{safe_name}-{str(incident.id)[:8]}-{redaction_level}.md"
    return markdown, filename


_MD_HEADING = re.compile(r"^(#{1,6})\s+(.*)$")
_MD_BULLET = re.compile(r"^(\s*)[-*]\s+(.*)$")


def markdown_to_pdf(markdown: str, title: str = "Incident report") -> bytes:
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.lib.units import mm
    from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer

    buffer = io.BytesIO()
    document = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        title=title,
        leftMargin=18 * mm,
        rightMargin=18 * mm,
        topMargin=18 * mm,
        bottomMargin=18 * mm,
    )
    base = getSampleStyleSheet()
    body = ParagraphStyle("OZBody", parent=base["BodyText"], fontSize=9.5, leading=13)
    code = ParagraphStyle("OZCode", parent=body, fontName="Courier", fontSize=8)
    story = []

    for raw_line in markdown.splitlines():
        line = raw_line.rstrip()
        if not line:
            story.append(Spacer(1, 4))
            continue
        heading = _MD_HEADING.match(line)
        if heading:
            level = len(heading.group(1))
            style = ParagraphStyle(
                f"OZH{level}",
                parent=base["Heading1"] if level <= 2 else base["Heading2"],
                fontSize=16 - level,
                leading=20 - level,
                spaceBefore=8,
                spaceAfter=4,
            )
            story.append(Paragraph(escape(heading.group(2)), style))
            continue
        if line.startswith("|") and line.endswith("|"):
            cells = [cell.strip() for cell in line.strip("|").split("|")]
            if all(set(cell) <= {"-", " "} for cell in cells):
                continue
            story.append(Paragraph(" &nbsp;·&nbsp; ".join(escape(c) for c in cells), code))
            continue
        bullet = _MD_BULLET.match(line)
        if bullet:
            story.append(Paragraph("• " + escape(bullet.group(2)), body, bulletText="•"))
            continue
        if line.startswith(">"):
            story.append(Paragraph(f"<i>{escape(line.lstrip('> '))}</i>", body))
            continue
        if line.startswith("---"):
            story.append(Spacer(1, 6))
            continue
        story.append(Paragraph(escape(line), body))

    document.build(story)
    return buffer.getvalue()


def render_report(
    session: Session, incident: Incident, *, fmt: str, redaction_level: str = "standard"
) -> ReportPayload:
    markdown, filename = build_markdown(session, incident, redaction_level=redaction_level)
    if fmt == "md":
        return ReportPayload(
            content=markdown.encode("utf-8"),
            filename=filename,
            media_type="text/markdown; charset=utf-8",
            redaction_level=redaction_level,
        )
    if fmt == "pdf":
        pdf = markdown_to_pdf(markdown, title=incident.title)
        return ReportPayload(
            content=pdf,
            filename=filename[:-3] + ".pdf",
            media_type="application/pdf",
            redaction_level=redaction_level,
        )
    raise ValueError("unsupported report format")


__all__ = ["ReportPayload", "build_markdown", "markdown_to_pdf", "render_report"]
